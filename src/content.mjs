export const nameOf = (id) => INGREDIENTS.find((i) => i.id === id)?.name ?? id;
export function validateContent() {
  const ids = new Set(INGREDIENTS.map((i) => i.id));
  if (
    ids.size !== INGREDIENTS.length ||
    new Set(TICKETS.map((t) => t.id)).size !== TICKETS.length
  )
    throw Error('Duplicate content ID');
  for (const t of TICKETS) {
    const all = [...t.required, ...t.optional, ...t.forbidden];
    if (
      !t.required.length ||
      t.required.length + t.optional.length > 4 ||
      all.some((id) => !ids.has(id)) ||
      new Set(all).size !== all.length
    )
      throw Error('Invalid ticket: ' + t.id);
  }
  return true;
}
